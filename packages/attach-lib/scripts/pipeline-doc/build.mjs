#!/usr/bin/env node
// Write docs/pipeline.md: intro.md, then a diagram and a table of the steps Attach.parse runs (from PARSE_STEPS and
// fixup_passes, through scripts/pipeline-trace.mjs), then walkthroughs of a few properties (stages.mjs --markdown,
// WALKTHROUGHS).
//   yarn docs:pipeline   (or node scripts/pipeline-doc/build.mjs, after yarn build)
// Reads dist/ and test/linux, test/dt-schema; the processed schema of test/linux (scripts/processed-schema.mjs) if
// there is one. What the walkthroughs show depends on those trees: regenerate after a pipeline change or a bump.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { STEP_INFO, STEP_TREE } from "../pipeline-trace.mjs";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "../..");
const out = join(root, "docs/pipeline.md");

/** The properties the walkthroughs follow, each showing other steps, and what to look at in it. */
const WALKTHROUGHS = [
  {
    binding: "iio/accel/adi,adxl345.yaml", property: "compatible",
    shows: "A `oneOf` of a fallback list and an enum. The walk fixes each branch first (`at /oneOf/<n>`), `branch_counts` bounds the property by them, and `translate` makes one `list<enum>` whose options are whole values: the pair `adi,adxl346`, `adi,adxl345` is one option.",
  },
  {
    binding: "iio/adc/adi,ad7124.yaml", property: "reg",
    shows: "`redefinitions` merges in what `spi-peripheral-props.yaml` says of `reg` (the chip select's bounds), `dt_type` gives it the type dt-schema gives the name (an `address`), and `translate` makes the address a matrix: one row of one cell.",
  },
  {
    binding: "iio/adc/adi,ad7124.yaml", property: "reg", pattern: "^channel@([0-9]|1[0-5])$",
    shows: "A child node's `reg` bounded as a number: the `reg` fixup makes it one entry of one cell with those bounds.",
  },
  {
    binding: "iio/adc/adi,ad4130.yaml", property: "adi,excitation-current-0-nanoamp", pattern: "^channel@([0-9a-f])$",
    shows: "A unit suffix (`-nanoamp`) makes the property a list of numbers: `unit_suffix` moves its `enum` to the cells, `items_size` makes it one value, and `dt_type` names the type dt-schema gives the suffix, a `uint32-array`.",
  },
];

const id = (key) => key.replaceAll(/[^A-Za-z0-9]/g, "_");
const title = (key) => key.split(".").join(" › ");
const cell = (text) => text.replaceAll("|", "\\|").replaceAll("\n", " ");

/** The steps as a Mermaid flowchart: the stages top to bottom, the fixup passes inside theirs, a walk's fixups left to right. */
function diagram() {
  const lines = ["```mermaid", "flowchart TD"];
  const chain = (nodes, indent) => {
    for (const [index, node] of nodes.entries()) {
      if (node.children === undefined) {
        lines.push(`${indent}${id(node.key)}["${node.key.split(".").at(-1)}"]`);
      } else {
        lines.push(`${indent}subgraph ${id(node.key)}["${node.key.split(".").at(-1)}"]`);
        lines.push(`${indent}  direction ${node.kind === "walk" ? "LR" : "TB"}`);
        chain(node.children, `${indent}  `);
        lines.push(`${indent}end`);
      }
      if (index > 0) { lines.push(`${indent}${id(nodes[index - 1].key)} --> ${id(node.key)}`); }
    }
  };
  chain(STEP_TREE, "  ");
  lines.push("```");
  return lines.join("\n");
}

/** Every step with what it does and what it ports, in the order they run. */
function table() {
  const rows = ["| step | what it does | dt-schema |", "| --- | --- | --- |"];
  const add = (node) => {
    const { summary, counterpart } = STEP_INFO.get(node.key);
    rows.push(`| \`${title(node.key)}\` | ${cell(summary)} | ${counterpart === undefined ? "" : `\`${counterpart}\``} |`);
    for (const child of node.children ?? []) { add(child); }
  };
  for (const node of STEP_TREE) { add(node); }
  return rows.join("\n");
}

/** stages.mjs's markdown for one property, its headings one level down and what it shows under the first. */
function walkthrough({ binding, property, pattern, shows }) {
  const markdown = execFileSync("node", [
    join(root, "scripts/repros/stages.mjs"), binding, property, ...(pattern === undefined ? [] : ["--pattern", pattern]), "--markdown",
  ], { encoding: "utf8" });
  let fenced = false;
  const lines = markdown.split("\n").map((line) => {
    if (line.startsWith("```")) { fenced = !fenced; }
    return !fenced && line.startsWith("#") ? `#${line}` : line;
  });
  return [lines[0], "", shows, ...lines.slice(1)].join("\n").trimEnd();
}

const commit = (tree) => execFileSync("git", ["-C", join(root, tree), "rev-parse", "--short=12", "HEAD"], { encoding: "utf8" }).trim();

const document = [
  `<!-- Generated by yarn docs:pipeline (scripts/pipeline-doc/build.mjs): edit scripts/pipeline-doc/intro.md, the steps' summaries (PIPELINE_STAGES, fixup_passes, PARSE_STEPS) or the walkthroughs' list, not this file. -->`,
  "",
  readFileSync(join(here, "intro.md"), "utf8").trimEnd(),
  "",
  "## The steps",
  "",
  "`source` is the binding as its file has it. The stages run top to bottom; the fixup passes run inside `fixups`, and each walk applies its fixups (left to right) to every node schema and property.",
  "",
  diagram(),
  "",
  table(),
  "",
  "## Walkthroughs",
  "",
  `Generated from Linux at \`${commit("test/linux")}\` and dt-schema at \`${commit("test/dt-schema")}\`.`,
  "",
  WALKTHROUGHS.map(walkthrough).join("\n\n"),
  "",
].join("\n");

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, document);
console.error(`wrote ${out}`);
