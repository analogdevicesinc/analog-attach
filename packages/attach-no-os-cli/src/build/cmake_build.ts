/*
 * Driving the no-OS CMake build.
 *
 * no-OS replaced Make with CMake + Kconfig, so a build is no longer one command: it
 * is a configure step bound to a board preset, then a build step. Both `aa build` and
 * `aa deploy` need the same plan, so it is worked out once here.
 *
 * There are two build contexts, and the no-OS root behaves differently in each:
 *
 *   out-of-tree  the project is the top-level CMake source. Its own CMakeLists pulls
 *                no-OS in with add_subdirectory, and the root picks up `project.conf`
 *                by itself. Configure runs in the project directory.
 *   in-tree      the project lives in <no-OS>/projects/<name>/, and the no-OS root is
 *                the top-level source. It only descends into a project when told
 *                which defconfig to use, so configure runs from the no-OS root with
 *                -DPROJECT_DEFCONFIG=<name>/project.conf.
 *
 * `no_os_build.py` cannot do the out-of-tree case at all (it discovers projects by
 * scanning `projects/` and builds paths relative to it), which is why CMake is invoked
 * directly rather than through it.
 */
import { execFileSync, spawn } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import type { Result } from "attach-no-os-lib";
import { ok, error } from "attach-no-os-lib";

// Presets need 3.28, even though the no-OS root itself only asks for 3.27.
const REQUIRED_CMAKE = [3, 28, 0] as const;

const PRESETS_FILENAME = "CMakePresets.json";

// The name codegen gives the preset that pins the generated project to its board.
const PROJECT_PRESET = "project";

export type BuildPlan = {
	mode: "in-tree" | "out-of-tree";
	project_name: string;
	board: string;
	// The preset to configure with. Out-of-tree this is normally the project's own
	// `project` preset, which already carries the board and the build directory; a
	// board override has to name the board preset directly instead.
	preset: string;
	// Directory `cmake --preset` runs in: the project out-of-tree, the no-OS root in.
	source_directory: string;
	binary_directory: string;
	configure_arguments: string[];
	elf_path: string;
};

/**
 * The board a generated project was configured for, read back out of its own
 * CMakePresets.json. Codegen writes a `project` preset that inherits the board
 * preset, so the choice travels with the project and does not have to be repeated on
 * every build.
 */
export function board_from_project(project_path: string): Result<string> {
	const presets_path = path.join(project_path, PRESETS_FILENAME);
	if (!fs.existsSync(presets_path)) {
		return error(`No ${PRESETS_FILENAME} in ${project_path}. Was this project generated by 'aa generate'?`, presets_path);
	}

	let parsed: unknown;
	try {
		parsed = JSON.parse(fs.readFileSync(presets_path, "utf8"));
	} catch (parse_error) {
		const reason = parse_error instanceof Error ? parse_error.message : String(parse_error);
		return error(`Failed to parse ${presets_path}: ${reason}`, presets_path);
	}

	const presets = (parsed as { configurePresets?: unknown }).configurePresets;
	if (!Array.isArray(presets)) {
		return error(`${presets_path} defines no configurePresets`, presets_path);
	}

	for (const entry of presets) {
		if (typeof entry !== "object" || entry === null) {
			continue;
		}
		const preset = entry as Record<string, unknown>;
		if (preset.name === PROJECT_PRESET && typeof preset.inherits === "string") {
			return ok(preset.inherits);
		}
	}

	return error(`${presets_path} has no '${PROJECT_PRESET}' preset naming a board. Pass the board explicitly.`, presets_path);
}

/**
 * Work out how to build the project at `project_path`.
 *
 * `board` overrides what the project records, which is what makes building the same
 * sources for a second board a one-flag change.
 */
export function plan_build(project_path: string, noos_path: string, board_override?: string): Result<BuildPlan> {
	const project_name = path.basename(project_path);

	let board = board_override;
	if (board === undefined) {
		const recorded = board_from_project(project_path);
		if (!recorded.ok) {
			return recorded;
		}
		board = recorded.value;
	}

	// In-tree means literally sitting in <no-OS>/projects/: that is the only layout
	// projects/CMakeLists.txt can add_subdirectory into. Compared through realpath so
	// a symlinked checkout is not mistaken for an out-of-tree project.
	const projects_directory = path.join(noos_path, "projects");
	const in_tree = fs.existsSync(projects_directory)
		&& path.dirname(fs.realpathSync(project_path)) === fs.realpathSync(projects_directory);

	if (in_tree) {
		// The build directory carries the project name because every in-tree project
		// shares the no-OS root as its source directory.
		const binary_directory = path.join(noos_path, "build", `${project_name}-${board}`);
		return ok({
			mode: "in-tree",
			project_name: project_name,
			board: board,
			preset: board,
			source_directory: noos_path,
			binary_directory: binary_directory,
			// Relative to projects/: the root splits the directory off this path to
			// learn which project to descend into.
			configure_arguments: [`-DPROJECT_DEFCONFIG=${project_name}/project.conf`],
			elf_path: path.join(binary_directory, "build", `${project_name}.elf`),
		});
	}

	const binary_directory = path.join(project_path, "build", board);
	return ok({
		mode: "out-of-tree",
		project_name: project_name,
		board: board,
		preset: board_override === undefined ? PROJECT_PRESET : board,
		source_directory: project_path,
		binary_directory: binary_directory,
		// The root finds project.conf in the top-level source directory on its own.
		configure_arguments: [],
		elf_path: path.join(binary_directory, "build", `${project_name}.elf`),
	});
}

function tool_version(command: string, arguments_: string[]): string | undefined {
	try {
		return execFileSync(command, arguments_, { encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] });
	} catch {
		return undefined;
	}
}

/*
 * Build inputs that no Kconfig symbol can carry, keyed by the board's vendor.
 *
 * These are files and paths from a vendor's own tooling - a CubeMX project, a Vivado
 * hardware export - so codegen cannot produce them and `$config` cannot name them. They
 * only surface as a configure failure, which is why the hint is attached there rather
 * than checked up front: a build that would have worked must not be refused on the
 * strength of a guess about the user's SDK.
 */
const VENDOR_PREREQUISITES: Record<string, string> = {
	stm32: "stm32 needs a CubeMX project for the board. cmake/stm32/stm32_platform_sdk.cmake looks for "
		+ "<board>.ioc under projects/<project>/, so an out-of-tree build additionally needs an absolute "
		+ "-DCONFIG_STM32_IOC_PATH=<path to the .ioc>.",
	xilinx: "xilinx needs the Vivado hardware export: pass -DHARDWARE=<system.xsa>.",
	pico: "pico needs the Raspberry Pi Pico SDK: set PICO_SDK_PATH to a checkout of it.",
	aducm3029: "aducm3029 needs the CrossCore/ADuCM302x SDK on the toolchain path.",
};

/**
 * What is missing when a configure fails for a board whose platform needs an input from
 * outside no-OS, or undefined when the vendor needs nothing beyond the toolchain (as
 * maxim does, whose SDK comes from its toolchain file).
 */
export function missing_prerequisite_hint(vendor: string): string | undefined {
	return VENDOR_PREREQUISITES[vendor];
}

/**
 * Check the things whose absence produces a confusing failure much later, with a
 * message that says what to install.
 */
export function preflight(noos_path: string): Result<string[]> {
	const notes: string[] = [];

	const cmake = tool_version("cmake", ["--version"]);
	if (cmake === undefined) {
		return error("cmake was not found on PATH. Install CMake 3.28 or newer.", "cmake");
	}

	const version = /(\d+)\.(\d+)\.(\d+)/.exec(cmake);
	if (version) {
		const found = [Number(version[1]), Number(version[2]), Number(version[3])];
		const as_number = (parts: readonly number[]) => (parts[0] ?? 0) * 1_000_000 + (parts[1] ?? 0) * 1000 + (parts[2] ?? 0);
		if (as_number(found) < as_number(REQUIRED_CMAKE)) {
			return error(
				`CMake ${found.join(".")} is too old; the no-OS presets need ${REQUIRED_CMAKE.join(".")} or newer.`,
				"cmake",
			);
		}
	}

	// Ninja is not a nice-to-have: every no-OS preset names it as the generator, so a
	// missing ninja fails the configure step with nothing built.
	if (tool_version("ninja", ["--version"]) === undefined) {
		return error("ninja was not found on PATH, and every no-OS board preset uses it as the generator. Install it (apt install ninja-build).", "ninja");
	}

	// The first configure creates the Python venv inside the no-OS *source* tree, not
	// the build directory, so a read-only checkout fails there rather than here.
	try {
		fs.accessSync(noos_path, fs.constants.W_OK);
	} catch {
		return error(`The no-OS checkout at ${noos_path} is not writable, and the first configure creates .no_os_venv inside it.`, "no_os_path");
	}

	if (!fs.existsSync(path.join(noos_path, ".no_os_venv"))) {
		notes.push("First build in this checkout: CMake will create .no_os_venv and install kconfiglib, which takes a while.");
	}

	if (!fs.existsSync(path.join(noos_path, PRESETS_FILENAME))) {
		return error(`Missing ${PRESETS_FILENAME} in ${noos_path}. This no-OS checkout predates the CMake build system.`, "no_os_path");
	}

	return ok(notes);
}

export type CommandResult = { exit_code: number };

/**
 * Run a command with its output going straight to the terminal. Configure output is
 * never captured or summarised on purpose: kconfiglib reports an unsatisfied `depends
 * on` as a warning there, and that warning is the earliest sign that a project.conf is
 * missing a symbol - the alternative is a link error much later.
 */
export function run(command: string, arguments_: string[], cwd: string): Promise<CommandResult> {
	return new Promise((resolve) => {
		const child = spawn(command, arguments_, { cwd, stdio: "inherit" });
		child.on("close", (code) => resolve({ exit_code: code ?? 1 }));
		child.on("error", () => resolve({ exit_code: 1 }));
	});
}

/** Run a shell string, for the `build_command`/`deploy_command` override. */
export function run_shell(command: string, cwd: string): Promise<CommandResult> {
	return new Promise((resolve) => {
		const child = spawn(command, [], { cwd, shell: true, stdio: "inherit" });
		child.on("close", (code) => resolve({ exit_code: code ?? 1 }));
		child.on("error", () => resolve({ exit_code: 1 }));
	});
}

export function configure_arguments(plan: BuildPlan, extra: string[] = []): string[] {
	return [
		"--preset", plan.preset,
		"-B", plan.binary_directory,
		...plan.configure_arguments,
		...extra,
	];
}

export function build_arguments(plan: BuildPlan, target: string): string[] {
	return ["--build", plan.binary_directory, "--target", target];
}
